CREATE TABLE audit_logs (

    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    event_id UUID NOT NULL,

    event_type VARCHAR(100) NOT NULL,

    service_name VARCHAR(100) NOT NULL,

    user_id UUID,

    organization_id UUID,

    workspace_id UUID,

    project_id UUID,

    resource_type VARCHAR(100),

    resource_id UUID,

    action VARCHAR(100) NOT NULL,

    status VARCHAR(30) NOT NULL,

    ip_address INET,

    user_agent TEXT,

    request_id UUID,

    event_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP

);
-- Search logs by event time
CREATE INDEX idx_audit_logs_event_timestamp
ON audit_logs(event_timestamp);

-- Search logs for a specific user
CREATE INDEX idx_audit_logs_user_id
ON audit_logs(user_id);

-- Search logs generated by a specific service
CREATE INDEX idx_audit_logs_service_name
ON audit_logs(service_name);

-- Trace an entire request across all services
CREATE INDEX idx_audit_logs_request_id
ON audit_logs(request_id);
